/** 'system' follows the OS language: Arabic for any ar-* locale, English otherwise. */
export const resolveLang = (setting, locale = '') => (setting === 'en' || setting === 'ar' ? setting : /^ar\b/i.test(locale) ? 'ar' : 'en')

